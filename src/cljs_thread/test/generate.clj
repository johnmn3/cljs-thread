(defn generate-runner-source
  "Generate runner ClojureScript source for the given tests and tier.

   Options:
     :runner-ns     - namespace symbol for the generated runner
     :tier          - :pure, :slab, or :worker
     :reporter      - reporter keyword (nil for default)
     :timeout-ms    - timeout in ms (tier defaults if nil)
     :future-count  - worker pool size (only for :worker tier)"
  [tests {:keys [runner-ns tier reporter timeout-ms future-count]
          :or   {runner-ns 'cljs-thread.test.generated-runner}}]
  (case tier
    :pure   (gen-pure-runner runner-ns tests {:reporter reporter :timeout-ms timeout-ms})
    :slab   (gen-slab-runner runner-ns tests {:reporter reporter :timeout-ms timeout-ms})
    :worker (gen-worker-runner runner-ns tests {:reporter reporter :timeout-ms timeout-ms
                                                 :future-count future-count})))

(defn write-runner!
  "Generate and write a runner .cljs file. Returns the file path."
  [tests opts]
  (let [source (generate-runner-source tests opts)
        ;; Convert ns to path: cljs-thread.test.generated-runner → cljs_thread/test/generated_runner.cljs
        ns-path (-> (str (or (:runner-ns opts) 'cljs-thread.test.generated-runner))
                    (str/replace "." "/")
                    (str/replace "-" "_")
                    (str ".cljs"))
        file-path (str "target/generated-test/" ns-path)]
    (io/make-parents (io/file file-path))
    (spit file-path source)
    file-path))

