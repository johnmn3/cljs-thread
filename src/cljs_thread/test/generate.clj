(defn generate-shadow-config
  "Generate a shadow-cljs build config map for the test run.
   Used with the programmatic API (shadow.cljs.devtools.api/compile*).

   Options:
     :build-id    - keyword build ID (default :test-run)
     :tier        - :pure, :slab, or :worker
     :runner-ns   - namespace symbol for the runner
     :output-path - JS output path
     :opt-level   - :none, :basic, or :advanced
     :source-paths - extra source paths"
  [{:keys [build-id tier runner-ns output-path opt-level source-paths]
    :or   {build-id    :test-run
           runner-ns   'cljs-thread.test.generated-runner
           output-path "target/test-run/test.js"
           opt-level   :none}}]
  (let [base {:build-id build-id
              :target   :node-script
              :main     (symbol (str runner-ns) "main")
              :output-to output-path
              :compiler-options {:load-tests true}
              :source-paths (into ["src" "test"] (or source-paths []))}]
    (cond-> base
      (= opt-level :basic)
      (assoc-in [:compiler-options :optimizations] :simple)

      ;; :advanced uses default Closure optimizations
      ;; :none uses no optimizations (development)
      )))

(defn generate-browser-shadow-config
  "Generate a shadow-cljs browser build config for the test run."
  [{:keys [build-id tier runner-ns output-dir opt-level source-paths]
    :or   {build-id   :test-browser-run
           runner-ns  'cljs-thread.test.generated-runner
           output-dir "target/test-run-browser"
           opt-level  :none}}]
  (let [base {:build-id build-id
              :target     :browser
              :output-dir output-dir
              :asset-path "."
              :modules    {:main {:init-fn (symbol (str runner-ns) "init!")}}
              :compiler-options {:load-tests true}
              :source-paths (into ["src" "test"] (or source-paths []))
              :js-options {:resolve {"worker_threads" {:target :browser :global "null"}
                                     "wabt"           {:target :browser :global "null"}}}}]
    (cond-> base
      (= opt-level :basic)
      (assoc-in [:compiler-options :optimizations] :simple))))
